#!/usr/bin/env python
"""Dev tool (NOT part of the unit tests): capture short REAL model outputs from llama-server on port 8001.

Usage: capture_real.py OUT.json [case_name ...]

Cases that say "forced" prepend a short, fixed thinking segment to the response (so the continuation is short);
everything after the forced prefix is generated by the real model (greedy). Cases without a prefix are natural
generations truncated at n_predict tokens. The fixture stores both the prompt and the full output token ids.
"""
import json
import sys
import time
import urllib.request

BASE = "http://127.0.0.1:8001"
THINK = "<|message_model|><|content_thinking|>%s<|end_message|>"
TOOLS_WEATHER = [{"type": "function", "function": {
    "name": "get_weather", "description": "Get the current weather for a city.",
    "parameters": {"type": "object", "properties": {"city": {"type": "string"}}, "required": ["city"]}}}]
TOOLS_BOTH = TOOLS_WEATHER + [{"type": "function", "function": {
    "name": "get_time", "description": "Get the current time in a city.",
    "parameters": {"type": "object", "properties": {"city": {"type": "string"}}, "required": ["city"]}}}]

CASES = {
    "plain_natural": dict(messages=[{"role": "user", "content": "Reply with just the word: pong"}],
                          prefix="", n_predict=40),
    "plain_forced": dict(messages=[{"role": "user", "content": "Reply with just the word: pong"}],
                         prefix=THINK % "The user wants me to say pong.", n_predict=24),
    "tool_forced": dict(messages=[{"role": "user", "content": "What is the weather in Paris?"}], tools=TOOLS_WEATHER,
                        prefix=THINK % "I should look up the weather in Paris with get_weather.", n_predict=48),
    "tool_result_forced": dict(
        messages=[{"role": "user", "content": "What is the weather in Paris?"},
                  {"role": "assistant", "content": None, "tool_calls": [
                      {"id": "call_1", "type": "function",
                       "function": {"name": "get_weather", "arguments": {"city": "Paris"}}}]},
                  {"role": "tool", "tool_call_id": "call_1", "name": "get_weather", "content": "18C and sunny"}],
        tools=TOOLS_WEATHER, prefix=THINK % "The tool says 18C and sunny, so I can answer now.", n_predict=40),
    "parallel_tools_forced": dict(
        messages=[{"role": "user", "content": "What is the weather in Paris and the time in Tokyo?"}],
        tools=TOOLS_BOTH, prefix=THINK % "I need to call both tools.", n_predict=80),
}


def post(path, obj, timeout=900):
    req = urllib.request.Request(BASE + path, data=json.dumps(obj).encode(),
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read())


def main():
    out_path = sys.argv[1]
    names = sys.argv[2:] or list(CASES)
    try:
        out = json.load(open(out_path))
    except Exception:
        out = {}
    for name in names:
        c = CASES[name]
        body = {"messages": c["messages"]}
        if c.get("tools"):
            body["tools"] = c["tools"]
        prompt = post("/apply-template", body)["prompt"]
        prompt = prompt.replace("Thinking effort level: 0.9", "Thinking effort level: 0")  # keep thinking short
        text = prompt + c["prefix"]
        ids = post("/tokenize", {"content": text, "add_special": False, "parse_special": True})["tokens"]
        t0 = time.time()
        r = post("/completion", {"prompt": ids, "n_predict": c["n_predict"], "temperature": 0.0, "top_k": 1,
                                 "seed": 1, "return_tokens": True, "cache_prompt": True, "stream": False})
        dt = time.time() - t0
        gen = r.get("tokens", [])
        prefix_ids = post("/tokenize", {"content": c["prefix"], "add_special": False, "parse_special": True})["tokens"] \
            if c["prefix"] else []
        out[name] = {
            "messages": c["messages"], "tools": c.get("tools"), "prompt_text": prompt, "forced_prefix": c["prefix"],
            "prompt_token_ids": post("/tokenize", {"content": prompt, "add_special": False, "parse_special": True})["tokens"],
            "forced_prefix_ids": prefix_ids, "generated_ids": gen, "n_predict": c["n_predict"],
            "stop_type": r.get("stop_type"), "stopped_eos": r.get("stopped_eos"), "stopped_limit": r.get("stopped_limit"),
            "server_content": r.get("content"), "wall_s": round(dt, 1), "timings": r.get("timings"),
        }
        json.dump(out, open(out_path, "w"), indent=1)
        print(name, "gen", len(gen), "tokens in", round(dt, 1), "s; stop", r.get("stop_type"), flush=True)


if __name__ == "__main__":
    main()
